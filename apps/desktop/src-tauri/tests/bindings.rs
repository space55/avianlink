//! Checks that the frontend's view of the IPC surface matches the backend's.
//!
//! `ts-rs` generates the *types*; nothing generates the command and event
//! *names*, which are strings on both sides. A renamed command compiles
//! cleanly in Rust and typechecks cleanly in TypeScript, and then does nothing
//! at runtime. These tests are the thing that catches that.
//!
//! They read the source files rather than the generated bindings, because the
//! names live in `commands.rs`'s handler list and in `events::ALL`.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

/// The crate root (`apps/desktop/src-tauri`).
fn crate_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn read(relative: &str) -> String {
    let path: PathBuf = crate_root().join(relative);
    std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()))
}

/// Command names from the `command_handlers!` list in `commands.rs`.
fn backend_commands() -> BTreeSet<String> {
    read("src/commands.rs")
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            let rest = line.strip_prefix("$crate::commands::")?;
            Some(rest.trim_end_matches(',').to_string())
        })
        .collect()
}

/// Names listed in the TypeScript client's `COMMAND_NAMES` / `EVENT_NAMES`.
fn frontend_names(source: &str, constant: &str) -> BTreeSet<String> {
    let start = source
        .find(&format!("export const {constant} = ["))
        .unwrap_or_else(|| panic!("{constant} not found in client.ts"));
    let body = &source[start..];
    let end = body.find("] as const;").expect("unterminated name list");
    body[..end]
        .lines()
        .filter_map(|line| {
            let line = line.trim().trim_end_matches(',');
            let inner = line.strip_prefix('\'')?.strip_suffix('\'')?;
            Some(inner.to_string())
        })
        .collect()
}

#[test]
fn the_frontend_knows_every_command_the_backend_registers() {
    let backend = backend_commands();
    assert!(
        backend.len() >= 14,
        "parsed too few commands ({}); the handler list's shape probably changed",
        backend.len()
    );
    let frontend = frontend_names(&read("../src/lib/ipc/client.ts"), "COMMAND_NAMES");
    assert_eq!(
        backend, frontend,
        "src/lib/ipc/client.ts and commands.rs disagree about the command list"
    );
}

#[test]
fn the_frontend_knows_every_event_the_backend_emits() {
    let backend: BTreeSet<String> = avianlink_desktop_lib::events::ALL
        .iter()
        .map(|s| s.to_string())
        .collect();
    let frontend = frontend_names(&read("../src/lib/ipc/client.ts"), "EVENT_NAMES");
    assert_eq!(
        backend, frontend,
        "src/lib/ipc/client.ts and events.rs disagree about the event list"
    );
}

#[test]
fn every_command_in_the_handler_list_is_actually_defined() {
    let source = read("src/commands.rs");
    for command in backend_commands() {
        assert!(
            source.contains(&format!("pub async fn {command}(")),
            "`{command}` is in the handler list but has no definition"
        );
    }
}

#[test]
fn the_generated_bindings_exist_and_are_marked_generated() {
    // `cargo test` regenerates this file; `scripts/desktop-ci.sh` then fails
    // if the working tree changed, which is what keeps the committed copy
    // honest (desktop DA-007).
    let bindings = read("../src/lib/ipc/bindings.ts");
    assert!(
        bindings.contains("Do not edit this file manually"),
        "bindings.ts lost its generated-file banner"
    );
    for expected in [
        "export type Message",
        "export type IpcError",
        "export type Link",
    ] {
        assert!(
            bindings.contains(expected),
            "bindings.ts is missing {expected}"
        );
    }
    assert!(
        !bindings.contains("bigint"),
        "a u64 crossed IPC without #[ts(type = \"number\")]; see ipc.rs"
    );
}

/// Parses one of the crate's JSON config files.
fn json(relative: &str) -> serde_json::Value {
    serde_json::from_str(&read(relative)).expect("config is not valid JSON")
}

#[test]
fn the_capability_file_grants_nothing_beyond_events() {
    // The app's own commands need no ACL grant. Anything else appearing here
    // widens what the webview can reach, and should be deliberate.
    let capabilities = json("capabilities/default.json");
    let granted: Vec<&str> = capabilities["permissions"]
        .as_array()
        .expect("permissions must be an array")
        .iter()
        .map(|p| p.as_str().expect("permissions must be strings"))
        .collect();
    assert_eq!(
        granted,
        vec!["core:event:allow-listen", "core:event:allow-unlisten"],
        "unexpected capability grants"
    );
    assert_eq!(
        capabilities["windows"].as_array().map(Vec::len),
        Some(1),
        "capabilities must be scoped to the main window"
    );
}

#[test]
fn the_production_csp_allows_no_remote_content() {
    let config = json("tauri.conf.json");
    let csp = config["app"]["security"]["csp"]
        .as_str()
        .expect("a production CSP must be set");
    // `default-src 'none'` plus an explicit allowlist. The only non-'self'
    // source is Tauri's own IPC endpoint.
    for required in [
        "default-src 'none'",
        "object-src 'none'",
        "frame-ancestors 'none'",
        "base-uri 'none'",
    ] {
        assert!(csp.contains(required), "CSP is missing `{required}`: {csp}");
    }
    let without_ipc = csp.replace("ipc:", "").replace("http://ipc.localhost", "");
    for forbidden in ["http://", "https://", "*", "unsafe-eval"] {
        assert!(
            !without_ipc.contains(forbidden),
            "production CSP allows `{forbidden}`: {csp}"
        );
    }
    // `style-src 'unsafe-inline'` is the one concession: Svelte sets inline
    // styles through the `style:` directive. Scripts must never get it.
    let script_src = csp
        .split(';')
        .find(|part| part.trim_start().starts_with("script-src"))
        .expect("no script-src");
    assert!(
        !script_src.contains("unsafe-inline"),
        "script-src must not allow inline scripts: {script_src}"
    );
}

#[test]
fn the_asset_protocol_is_disabled() {
    let config = json("tauri.conf.json");
    assert_eq!(
        config["app"]["security"]["assetProtocol"]["enable"],
        serde_json::Value::Bool(false),
        "the asset protocol must stay off: it is a filesystem read primitive"
    );
    assert_eq!(
        config["app"]["withGlobalTauri"],
        serde_json::Value::Bool(false),
        "the global Tauri object would expose the IPC to any injected script"
    );
}

#[test]
fn docs_exist_for_everything_this_crate_promises() {
    let docs = crate_root().join("../docs");
    for name in ["ipc.md", "decisions.md", "api-requests.md"] {
        let path: &Path = &docs.join(name);
        assert!(path.exists(), "missing {}", path.display());
    }
}
