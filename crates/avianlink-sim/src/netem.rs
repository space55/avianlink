//! `tc netem` scripts generated from the simulator profiles
//! (`docs/hosting.md` §5). Checked into `scripts/netem/`; a test keeps them
//! in sync.

use crate::impair::{Jitter, LinkProfile};
use crate::Profile;

fn pct(p: f64) -> String {
    let s = format!("{:.3}", p * 100.0);
    let s = s.trim_end_matches('0').trim_end_matches('.');
    format!("{s}%")
}

/// The netem parameter string for a profile, outages aside.
pub fn netem_params(link: &LinkProfile) -> String {
    params(link, false)
}

/// The same with all packets lost (an outage).
pub fn netem_params_down(link: &LinkProfile) -> String {
    params(link, true)
}

fn params(link: &LinkProfile, down: bool) -> String {
    let mut p = Vec::new();
    let base = link.delay.base_ms;
    p.push(match link.delay.jitter {
        Jitter::None => format!("delay {base}ms"),
        // netem's default jitter is uniform around the mean.
        Jitter::Uniform { max_ms } => format!("delay {}ms {}ms", base + max_ms / 2, max_ms / 2),
        Jitter::Pareto {
            scale_ms, alpha, ..
        } => {
            let median = (scale_ms * (2f64.powf(1.0 / alpha) - 1.0)).round() as u64;
            format!(
                "delay {}ms {}ms distribution pareto",
                base + median,
                median.max(1)
            )
        }
    });
    let ge = link.loss;
    if down {
        p.push("loss 100%".to_string());
    } else if ge.loss_good > 0.0 || ge.loss_bad > 0.0 {
        p.push(format!(
            "loss gemodel {} {} {} {}",
            pct(ge.p_good_to_bad),
            pct(ge.p_bad_to_good),
            pct(ge.loss_bad),
            pct(ge.loss_good)
        ));
    }
    if link.bit_flip_prob > 0.0 {
        p.push(format!("corrupt {}", pct(link.bit_flip_prob)));
    }
    if link.duplicate_prob > 0.0 {
        p.push(format!("duplicate {}", pct(link.duplicate_prob)));
    }
    if link.reorder_prob > 0.0 {
        p.push(format!("reorder {} 50%", pct(link.reorder_prob)));
    }
    let bytes_per_s = if let Some(d) = link.duty {
        // Airtime as serialization: a per-byte rate plus a fixed per-packet
        // overhead expressed in bytes. The duty-cycle budget itself is
        // enforced by the engine.
        let per_byte = f64::from(d.airtime.per_byte_us.max(1));
        let rate = (1e6 / per_byte).round() as u64;
        let overhead = (f64::from(d.airtime.per_packet_us) / per_byte).round() as u64;
        p.push(format!("rate {}bit {overhead}", rate * 8));
        Some(rate)
    } else if let Some(r) = link.rate_bytes_per_sec {
        p.push(format!("rate {}bit", u64::from(r) * 8));
        Some(u64::from(r))
    } else {
        None
    };
    if let Some(r) = bytes_per_s {
        // Queue in packets, from the queue's time budget at ~64-byte packets.
        let limit = (link.queue_limit_ms * r / 1000 / 64).max(10);
        p.push(format!("limit {limit}"));
    }
    p.join(" ")
}

/// A complete POSIX shell script applying `profile` to the devices given as
/// arguments.
pub fn script(profile: Profile) -> String {
    let link = profile.link();
    let name = profile.name();
    let params = netem_params(&link);
    let params_down = netem_params_down(&link);
    let mut s = format!(
        r#"#!/bin/sh
# Generated by `cargo run -p avianlink-sim --bin netem-gen` from the
# `{name}` simulator profile (MTU {mtu}). Do not edit; regenerate.
# Usage (as root, Linux): {name}.sh DEV [DEV...]
# Apply on every interface whose egress should be impaired, e.g. both
# interfaces of a box routing between two hosts. Run the CLI with
# `--profile {name}` so the engine uses the same MTU and budget.
set -eu
[ $# -ge 1 ] || {{ echo "usage: $0 DEV [DEV...]" >&2; exit 2; }}
NETEM="{params}"
for dev in "$@"; do tc qdisc replace dev "$dev" root netem $NETEM; done
"#,
        mtu = link.mtu
    );
    match link.outage {
        None => s.push_str("echo \"netem: $NETEM\"\n"),
        Some(o) => {
            let (up, down) = (o.up_ms / 1000, o.down_ms / 1000);
            let draw = if o.randomize {
                "# Exponential durations, seeded from /dev/urandom.\n\
                 draw() { awk -v m=\"$1\" -v s=\"$(od -An -N4 -tu4 /dev/urandom)\" \\\n  \
                 'BEGIN { srand(s); r = rand(); if (r < 1e-9) r = 1e-9; printf \"%d\", -log(r) * m + 1 }'; }\n"
                    .to_string()
            } else {
                "draw() { echo \"$1\"; }\n".to_string()
            };
            s.push_str(&format!(
                r#"# Outages: up {up} s, down {down} s{kind}, all devices together.
NETEM_DOWN="{params_down}"
{draw}trap 'for dev in "$@"; do tc qdisc del dev "$dev" root 2>/dev/null || true; done' EXIT INT TERM
echo "netem: $NETEM (with outages; Ctrl-C to stop and clear)"
while :; do
  sleep "$(draw {up})"
  for dev in "$@"; do tc qdisc change dev "$dev" root netem $NETEM_DOWN; done
  echo "$(date +%T) link down"
  sleep "$(draw {down})"
  for dev in "$@"; do tc qdisc change dev "$dev" root netem $NETEM; done
  echo "$(date +%T) link up"
done
"#,
                kind = if o.randomize { " on average" } else { "" },
            ));
        }
    }
    s
}

/// `scripts/netem/clear.sh`.
pub fn clear_script() -> &'static str {
    "#!/bin/sh\n\
     # Removes netem qdiscs. Usage (as root): clear.sh DEV [DEV...]\n\
     set -eu\n\
     for dev in \"$@\"; do tc qdisc del dev \"$dev\" root 2>/dev/null || true; done\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_disaster_cellular() {
        let p = netem_params(&Profile::DisasterCellular.link());
        assert!(p.starts_with("delay "), "{p}");
        assert!(p.contains("distribution pareto"), "{p}");
        assert!(p.contains("loss gemodel 5% 10% 85% 10%"), "{p}");
        assert!(
            p.contains("corrupt 2%") && p.contains("duplicate 2%"),
            "{p}"
        );
        assert!(p.contains("rate 8000bit"), "{p}");
        let s = script(Profile::DisasterCellular);
        assert!(
            s.contains("NETEM_DOWN=\"delay") && s.contains("draw 300") && s.contains("draw 180")
        );
        let down = netem_params_down(&Profile::DisasterCellular.link());
        assert!(
            down.contains("loss 100%") && !down.contains("gemodel"),
            "{down}"
        );
    }

    #[test]
    fn maps_lora_airtime_and_clean() {
        let p = netem_params(&Profile::LoraLike.link());
        assert!(p.contains("rate 1952bit 39"), "{p}");
        assert_eq!(netem_params(&Profile::Clean.link()), "delay 5ms");
        assert!(!script(Profile::Clean).contains("while :"));
    }
}
